const slugify = (text) =>
    (text || '').toLowerCase().trim().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');

const toTitleCase = (str) => {
    if (!str) return '';
    return str
        .split(/[-_\s]+/)
        .map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
        .join(' ');
};

export function getCategorySeoData(categoryIdentifier, contextCategories = []) {
    if (!categoryIdentifier || categoryIdentifier === 'all') return null;

    const normalizedSlug = slugify(categoryIdentifier);

    // 1. Direct match in CATEGORY_SEO_DATA
    if (CATEGORY_SEO_DATA[normalizedSlug]) {
        return { slug: normalizedSlug, ...CATEGORY_SEO_DATA[normalizedSlug] };
    }

    // 2. Check alias map
    const aliasKey = CATEGORY_ALIASES[normalizedSlug] || CATEGORY_ALIASES[categoryIdentifier.toLowerCase().trim()];
    if (aliasKey && CATEGORY_SEO_DATA[aliasKey]) {
        return { slug: aliasKey, ...CATEGORY_SEO_DATA[aliasKey] };
    }

    // 3. Match against contextCategories by id or label
    if (Array.isArray(contextCategories)) {
        const matched = contextCategories.find(c =>
            slugify(c.id) === normalizedSlug ||
            slugify(c.label) === normalizedSlug ||
            c.id === categoryIdentifier ||
            c.label === categoryIdentifier
        );
        if (matched) {
            const matchedSlug = slugify(matched.id);
            if (CATEGORY_SEO_DATA[matchedSlug]) {
                return { slug: matchedSlug, ...CATEGORY_SEO_DATA[matchedSlug] };
            }
            const labelSlug = slugify(matched.label);
            if (CATEGORY_SEO_DATA[labelSlug]) {
                return { slug: labelSlug, ...CATEGORY_SEO_DATA[labelSlug] };
            }
            const aliasFromLabel = CATEGORY_ALIASES[labelSlug] || CATEGORY_ALIASES[matchedSlug];
            if (aliasFromLabel && CATEGORY_SEO_DATA[aliasFromLabel]) {
                return { slug: aliasFromLabel, ...CATEGORY_SEO_DATA[aliasFromLabel] };
            }

            // Fallback for custom dynamic category: format proper name
            const properName = matched.label || toTitleCase(matched.id);
            return {
                slug: matchedSlug,
                label: properName,
                title: `${properName} | Crochet Wali`,
                h1: `${properName} — Handmade Crochet Gifts`,
                metaDescription: `Shop handmade crochet ${properName.toLowerCase()} at Crochet Wali. Explore authentic artisanal creations handcrafted with love in India. Order online today!`.slice(0, 160),
                subheading: `Handcrafted ${properName.toLowerCase()} creations tailored for you.`,
                intro: `Explore our authentic range of handmade crochet ${properName.toLowerCase()} at Crochet Wali. Each item is individually crafted with high-quality yarn and attention to detail, making it a perfect gift or keepsake.`
            };
        }
    }

    // 4. Fallback for any unknown category string: format proper name (never raw hyphenated slug)
    const properName = toTitleCase(categoryIdentifier);
    return {
        slug: normalizedSlug,
        label: properName,
        title: `${properName} | Crochet Wali`,
        h1: `${properName} — Handmade Crochet Gifts`,
        metaDescription: `Shop handmade crochet ${properName.toLowerCase()} at Crochet Wali. Explore authentic artisanal creations handcrafted with love in India. Order online today!`.slice(0, 160),
        subheading: `Handcrafted ${properName.toLowerCase()} creations tailored for you.`,
        intro: `Explore our authentic range of handmade crochet ${properName.toLowerCase()} at Crochet Wali. Each item is individually crafted with high-quality yarn and attention to detail, making it a perfect gift or keepsake.`
    };
}
